import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { defaultHookCommand, readJsonObject, writeJsonIfChanged } from "./hook-command.ts";

const PLUGIN_REL = "./plugins/ctrlplane.mjs";

/**
 * OpenCode has no command hooks; it loads JS plugins. The generated plugin forwards
 * `tool.execute.before/after` and session events to the same hook command, and throws
 * (which blocks the tool) when the command exits 2 or answers with a deny/ask.
 */
export function buildOpenCodePlugin(hookCommand: string): string {
  return `// Generated by ctrlplane init. Re-run \`ctrlplane init\` to regenerate.
import { spawnSync } from "node:child_process";

const HOOK = ${JSON.stringify(hookCommand)};

function run(event, payload, directory) {
  const r = spawnSync(HOOK + " " + event + " --agent opencode", {
    shell: true,
    cwd: directory,
    input: JSON.stringify({ ...payload, cwd: directory, hook_event_name: event }),
    encoding: "utf8",
    timeout: 30000,
  });
  return { code: r.status ?? 0, out: (r.stdout || "").trim(), err: (r.stderr || "").trim() };
}

function enforce(result) {
  if (result.code === 2) throw new Error(result.err || "Blocked by ctrlplane");
  if (!result.out) return;
  try {
    const o = JSON.parse(result.out);
    const d = o.hookSpecificOutput && o.hookSpecificOutput.permissionDecision;
    if (d === "deny" || d === "ask") throw new Error(o.hookSpecificOutput.permissionDecisionReason || "Developer approval required");
  } catch (e) {
    if (e instanceof SyntaxError) return;
    throw e;
  }
}

export const CtrlplanePlugin = async ({ directory }) => ({
  "tool.execute.before": async (input, output) => {
    enforce(run("PreToolUse", { session_id: input.sessionID, tool_name: input.tool, tool_input: output.args }, directory));
  },
  "tool.execute.after": async (input, output) => {
    run("PostToolUse", { session_id: input.sessionID, tool_name: input.tool, tool_input: input.args, tool_response: output }, directory);
  },
  event: async ({ event }) => {
    const id = event && event.properties && (event.properties.sessionID || (event.properties.info && event.properties.info.id));
    if (event.type === "session.created") run("SessionStart", { session_id: id, source: "startup" }, directory);
    if (event.type === "session.idle") run("Stop", { session_id: id }, directory);
  },
});
`;
}

export function injectOpenCodePlugin(projectPath: string, hookCommand = defaultHookCommand()): {
  success: boolean;
  configPath: string;
  pluginPath: string;
  backupPath?: string;
  pluginAdded: boolean;
} {
  const dir = join(projectPath, ".opencode");
  const configPath = join(dir, "opencode.json");
  const pluginPath = join(dir, "plugins", "ctrlplane.mjs");

  mkdirSync(join(dir, "plugins"), { recursive: true });
  const source = buildOpenCodePlugin(hookCommand);
  const current = existsSync(pluginPath) ? readFileSync(pluginPath, "utf8") : "";
  if (current !== source) writeFileSync(pluginPath, source);

  const file = readJsonObject(configPath);
  const config = file.data;
  const plugins = Array.isArray(config.plugin) ? (config.plugin as unknown[]) : [];
  const pluginAdded = !plugins.includes(PLUGIN_REL);
  if (pluginAdded) plugins.push(PLUGIN_REL);
  config.plugin = plugins;
  if (!config.$schema) config.$schema = "https://opencode.ai/config.json";

  // Earlier versions registered a package that does not exist under the wrong key.
  if (Array.isArray(config.plugins)) {
    config.plugins = (config.plugins as unknown[]).filter((p) => p !== "@ctrlplane/opencode-plugin");
    if ((config.plugins as unknown[]).length === 0) delete config.plugins;
  }

  const written = writeJsonIfChanged(configPath, config, file.raw);
  return { success: true, configPath, pluginPath, backupPath: written.backupPath, pluginAdded };
}

export function removeOpenCodePlugin(projectPath: string): boolean {
  const configPath = join(projectPath, ".opencode", "opencode.json");
  const pluginPath = join(projectPath, ".opencode", "plugins", "ctrlplane.mjs");
  let changed = false;
  if (existsSync(pluginPath)) {
    rmSync(pluginPath);
    changed = true;
  }
  const file = readJsonObject(configPath);
  if (file.raw !== undefined && Array.isArray(file.data.plugin)) {
    file.data.plugin = (file.data.plugin as unknown[]).filter((p) => p !== PLUGIN_REL);
    changed = writeJsonIfChanged(configPath, file.data, file.raw).changed || changed;
  }
  return changed;
}
